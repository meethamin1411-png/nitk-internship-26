    # Registration Performance (IEEE)
    # ==========================================================

    def registration_performance(self):

        df = self.load_csv("registration_summary.csv")

        vehicles = df["Vehicle"]
        avg = df["Average"]
        ci = df["Confidence95"]

        fig, ax = plt.subplots(figsize=(8, 5))

        bars = ax.bar(
            vehicles,
            avg,
            yerr=ci,
            capsize=6,
            edgecolor="black",
            linewidth=1.5,
            color=self.colors()[:len(df)]
        )

        for bar, value in zip(bars, avg):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                value,
                f"{value:.2f}",
                ha="center",
                va="bottom",
                fontsize=9
            )

        ax.set_title("Vehicle Registration Performance", fontweight="bold")
        ax.set_xlabel("Vehicle ID")
        ax.set_ylabel("Registration Time (ms)")
        ax.grid(axis="y", linestyle="--", alpha=0.4)

        self.save_graph(
            fig,
            "registration_performance.png"
        )

