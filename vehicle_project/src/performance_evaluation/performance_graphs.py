import os
from pathlib import Path

import pandas as pd
import matplotlib.pyplot as plt
import numpy as np


class PerformanceGraphs:

    def __init__(self):

        # ---------------------------------------------------------
        # Folder Structure
        # ---------------------------------------------------------

        self.base_dir = Path(__file__).parent

        self.graph_data = self.base_dir / "graph_data"

        self.graph_results = self.base_dir / "graph_results"

        self.graph_results.mkdir(exist_ok=True)

        # ---------------------------------------------------------
        # IEEE Style
        # ---------------------------------------------------------

        self.set_ieee_style()

    # ==========================================================
    # IEEE Publication Style
    # ==========================================================

    def set_ieee_style(self):

        plt.style.use("default")

        plt.rcParams.update({

            "figure.figsize": (8, 5),

            "figure.dpi": 300,

            "savefig.dpi": 600,

            "font.family": "Times New Roman",

            "font.size": 11,

            "axes.labelsize": 12,

            "axes.titlesize": 13,

            "axes.titleweight": "bold",

            "axes.linewidth": 1.2,

            "axes.grid": True,

            "grid.alpha": 0.35,

            "grid.linestyle": "--",

            "grid.linewidth": 0.6,

            "legend.fontsize": 10,

            "xtick.labelsize": 10,

            "ytick.labelsize": 10,

            "xtick.direction": "in",

            "ytick.direction": "in"

        })

    # ==========================================================
    # Read CSV
    # ==========================================================

    def load_csv(self, filename):

        filepath = self.graph_data / filename

        if not filepath.exists():

            raise FileNotFoundError(
                f"\nCSV not found:\n{filepath}"
            )

        print(f"[✓] Loaded {filename}")

        return pd.read_csv(filepath)

    # ==========================================================
    # Save Graph
    # ==========================================================

    def save_graph(self, fig, filename):

        output = self.graph_results / filename

        fig.tight_layout()

        fig.savefig(
            output,
            dpi=600,
            bbox_inches="tight"
        )

        plt.close(fig)

        print(f"[✓] Saved {filename}")

    # ==========================================================
    # Common Axis Formatting
    # ==========================================================

    def format_axes(
        self,
        ax,
        title,
        xlabel,
        ylabel
    ):

        ax.set_title(title, weight="bold")

        ax.set_xlabel(xlabel)

        ax.set_ylabel(ylabel)

        ax.grid(
            True,
            linestyle="--",
            alpha=0.35
        )

        ax.set_axisbelow(True)

        for spine in ax.spines.values():
            spine.set_linewidth(1.2)

    # ==========================================================
    # Color Palette
    # ==========================================================

    def colors(self):

        return [

            "#4C72B0",

            "#55A868",

            "#C44E52",

            "#8172B2",

            "#CCB974",

            "#64B5CD",

            "#8C8C8C"

        ]

    # ==========================================================
    # Horizontal Bar Labels
    # ==========================================================

    def add_horizontal_labels(
        self,
        ax,
        bars,
        suffix=""
    ):

        for bar in bars:

            value = bar.get_width()

            ax.text(

                value,

                bar.get_y() + bar.get_height()/2,

                f"{value:.2f}{suffix}",

                va="center",

                fontsize=9

            )

    # ==========================================================
    # Vertical Bar Labels
    # ==========================================================

    def add_vertical_labels(
        self,
        ax,
        bars,
        suffix=""
    ):

        for bar in bars:

            value = bar.get_height()

            ax.text(

                bar.get_x() + bar.get_width()/2,

                value,

                f"{value:.2f}{suffix}",

                ha="center",

                va="bottom",

                fontsize=9

            )
