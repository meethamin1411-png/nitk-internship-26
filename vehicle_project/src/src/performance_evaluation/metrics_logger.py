"""
=========================================================
Performance Metrics Logger
PQC-VANET Project
=========================================================
Author : Meeth Amin
Purpose:
Collect all runtime performance metrics generated by the
PQC-VANET implementation and export them into CSV files.
=========================================================
"""

import os
import csv
from datetime import datetime


class MetricsLogger:

    def __init__(self):

        self.base_dir = os.path.dirname(os.path.abspath(__file__))
        self.output_dir = os.path.join(self.base_dir, "graph_data")

        os.makedirs(self.output_dir, exist_ok=True)

        # ===========================
        # Runtime Data Containers
        # ===========================

        self.registration_data = []

        self.key_generation_data = []

        self.authentication_data = []

        self.signature_data = []

        self.verification_data = []

        self.communication_data = []

        self.storage_data = []

        self.memory_data = []

        self.scalability_data = []

        self.encryption_data = []

        self.decryption_data = []

    ########################################################
    # Registration
    ########################################################

    def log_registration(
            self,
            vehicle_id,
            registration_time,
            memory_usage,
            status):

        self.registration_data.append({

            "Timestamp": datetime.now(),

            "Vehicle ID": vehicle_id,

            "Registration Time (ms)": registration_time,

            "Memory (KB)": memory_usage,

            "Status": status

        })

    ########################################################
    # Key Generation
    ########################################################

    def log_key_generation(
            self,
            vehicle_id,
            generation_time,
            public_key_size,
            private_key_size):

        self.key_generation_data.append({

            "Timestamp": datetime.now(),

            "Vehicle ID": vehicle_id,

            "Key Generation Time (ms)": generation_time,

            "Public Key Size (Bytes)": public_key_size,

            "Private Key Size (Bytes)": private_key_size

        })

    ########################################################
    # Authentication
    ########################################################

    def log_authentication(
            self,
            vehicle_id,
            authentication_time,
            latency,
            memory_usage,
            status):

        self.authentication_data.append({

            "Timestamp": datetime.now(),

            "Vehicle ID": vehicle_id,

            "Authentication Time (ms)": authentication_time,

            "Latency (ms)": latency,

            "Memory (KB)": memory_usage,

            "Status": status

        })

    ########################################################
    # Signature
    ########################################################

    def log_signature(
            self,
            vehicle_id,
            signing_time,
            signature_size):

        self.signature_data.append({

            "Timestamp": datetime.now(),

            "Vehicle ID": vehicle_id,

            "Signing Time (ms)": signing_time,

            "Signature Size (Bytes)": signature_size

        })

    ########################################################
    # Verification
    ########################################################

    def log_verification(
            self,
            vehicle_id,
            verification_time,
            status):

        self.verification_data.append({

            "Timestamp": datetime.now(),

            "Vehicle ID": vehicle_id,

            "Verification Time (ms)": verification_time,

            "Status": status

        })

    ########################################################
    # Communication
    ########################################################

    def log_communication(
            self,
            sender,
            receiver,
            protocol,
            message_size,
            packet_size,
            communication_cost,
            latency):

        self.communication_data.append({

            "Timestamp": datetime.now(),

            "Sender": sender,

            "Receiver": receiver,

            "Protocol": protocol,

            "Message Size (Bytes)": message_size,

            "Packet Size (Bytes)": packet_size,

            "Communication Cost (Bytes)": communication_cost,

            "Latency (ms)": latency

        })

    ########################################################
    # Storage
    ########################################################

    def log_storage(
            self,
            vehicle_id,
            public_key_size,
            private_key_size,
            signature_size,
            ciphertext_size,
            total_storage):

        self.storage_data.append({

            "Timestamp": datetime.now(),

            "Vehicle ID": vehicle_id,

            "Public Key": public_key_size,

            "Private Key": private_key_size,

            "Signature": signature_size,

            "Ciphertext": ciphertext_size,

            "Total Storage": total_storage

        })

    ########################################################
    # Memory
    ########################################################

    def log_memory(
            self,
            operation,
            peak_memory):

        self.memory_data.append({

            "Timestamp": datetime.now(),

            "Operation": operation,

            "Peak Memory (KB)": peak_memory

        })

    ########################################################
    # Scalability
    ########################################################

    def log_scalability(
            self,
            vehicles,
            authentication_time,
            communication_cost):

        self.scalability_data.append({

            "Vehicles": vehicles,

            "Authentication Time (ms)": authentication_time,

            "Communication Cost (Bytes)": communication_cost

        })

    ########################################################
    # Encryption
    ########################################################

    def log_encryption(
            self,
            vehicle_id,
            encryption_time,
            ciphertext_size):

        self.encryption_data.append({

            "Timestamp": datetime.now(),

            "Vehicle ID": vehicle_id,

            "Encryption Time (ms)": encryption_time,

            "Ciphertext Size": ciphertext_size

        })

    ########################################################
    # Decryption
    ########################################################

    def log_decryption(
            self,
            vehicle_id,
            decryption_time):

        self.decryption_data.append({

            "Timestamp": datetime.now(),

            "Vehicle ID": vehicle_id,

            "Decryption Time (ms)": decryption_time

        })

    ########################################################
    # Generic CSV Export
    ########################################################

    def export_csv(self, filename, data):

        if len(data) == 0:
            return

        filepath = os.path.join(self.output_dir, filename)

        with open(filepath, "w", newline="") as file:

            writer = csv.DictWriter(file, fieldnames=data[0].keys())

            writer.writeheader()

            writer.writerows(data)

    ########################################################
    # Export Everything
    ########################################################

    def export_all_csv(self):

        self.export_csv("registration.csv",
                        self.registration_data)

        self.export_csv("key_generation.csv",
                        self.key_generation_data)

        self.export_csv("authentication.csv",
                        self.authentication_data)

        self.export_csv("signature.csv",
                        self.signature_data)

        self.export_csv("verification.csv",
                        self.verification_data)

        self.export_csv("communication.csv",
                        self.communication_data)

        self.export_csv("storage.csv",
                        self.storage_data)

        self.export_csv("memory.csv",
                        self.memory_data)

        self.export_csv("scalability.csv",
                        self.scalability_data)

        self.export_csv("encryption.csv",
                        self.encryption_data)

        self.export_csv("decryption.csv",
                        self.decryption_data)